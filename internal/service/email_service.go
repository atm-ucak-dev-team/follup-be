// RegisterCredential registers or updates email credentials
func (s *EmailServiceImpl) RegisterCredential(ctx interface{}, cred *domain.EmailCredential) error {
	contextCast, ok := ctx.(context.Context)
	if !ok {
		return fmt.Errorf("invalid context type")
	}

	if cred.EmailAddress == "" {
		return fmt.Errorf("email address is required")
	}
	// Check if credential already exists
	existingCred, err := s.emailRepo.GetByUserID(contextCast, cred.UserID)
	if err != nil {
		// Credential doesn't exist, create new one
		return s.emailRepo.Create(contextCast, cred)
	}
	// Credential exists, update it
	cred.CreatedAt = existingCred.CreatedAt // Preserve creation time
	return s.emailRepo.Update(contextCast, cred)
}

