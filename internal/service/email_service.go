// connectIMAP connects to IMAP server and authenticates
func (s *EmailServiceImpl) connectIMAP(host, email, password string) (*client.Client, error) {
	// Connect to IMAP server
	imapClient, err := client.DialTLS(fmt.Sprintf("%s:993", host), &tls.Config{
		InsecureSkipVerify: false, // Use proper TLS verification in production
	})
	if err != nil {
		return nil, fmt.Errorf("failed to connect: %w", err)
	}

	// Authenticate
	if err := imapClient.Login(email, password); err != nil {
		imapClient.Close()
		return nil, fmt.Errorf("failed to authenticate: %w", err)
	}

	return imapClient, nil
}

// sendEmail sends an email using SMTP with STARTTLS
func (s *EmailServiceImpl) sendEmail(from, password, host, subject, body, messageId string, to []string) error {
	// Parse SMTP host
	parts := strings.Split(host, ":")
	smtpHost := parts[0]
	smtpPort := "587" // Default STARTTLS port

	if len(parts) > 1 {
		smtpPort = parts[1]
	}

	// Create email message
	msg := fmt.Sprintf(
		"From: %s\r\nTo: %s\r\nSubject: %s\r\nMessage-ID: %s\r\nDate: %s\r\n\r\n%s",
		from,
		strings.Join(to, ", "),
		subject,
		messageId,
		time.Now().Format(time.RFC1123Z),
		body,
	)

	// Split recipients for individual validation
	var recipients []string
	for _, addr := range to {
		if addr != "" {
			recipients = append(recipients, addr)
		}
	}

	// Connect to SMTP server and send
	auth := smtp.PlainAuth("", from, password, smtpHost)
	err := smtp.SendMail(
		fmt.Sprintf("%s:%s", smtpHost, smtpPort),
		auth,
		from,
		recipients,
		[]byte(msg),
	)

	if err != nil {
		return fmt.Errorf("failed to send email: %w", err)
	}

	return nil
}

func generateMessageID(emailFrom string) (string, error) {
	b := make([]byte, 16)
	_, err := rand.Read(b)
	if err != nil {
		return "", fmt.Errorf("failed to generate message ID: %w", err)
	}

	domain := emailFrom[strings.Index(emailFrom, "@")+1:]
	timestamp := time.Now().UnixNano()
	return fmt.Sprintf("<%d.%s@%s>", timestamp, hex.EncodeToString(b), domain), nil
}

